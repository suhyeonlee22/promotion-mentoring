import * as React from "react";
import { renderToStaticMarkup } from "react-dom/server";
import { expect, it, vi } from "vitest";
import { and, eq } from "drizzle-orm";
import { db } from "@/db/client";
import { seedAll } from "@/db/seed";
import * as s from "@/db/schema";
import { getCurrentUser, requireRole, type CurrentUser } from "@/lib/session";
import { createRound, runSelection, setManualAction, changeRoundStatus } from "@/services/rounds";
import { requestCorrection, approveCorrection, rejectCorrection, submitApplication, returnApplication, confirmApplication, registerResult, notifyResults } from "@/services/applications";
import { listNotifications, openNotification, unreadNotificationCount } from "@/services/notifications";
import MyPromotionPage from "../me/promotion/page";
import MyMailsPage from "../me/mails/page";
import ReviewPage from "./rounds/[roundId]/review-data/page";
import { POST } from "./rounds/[roundId]/review-data/csv/route";

vi.mock("@/lib/session", () => ({ requireRole: vi.fn(), getCurrentUser: vi.fn() }));
vi.mock("next/headers", () => ({ headers: async () => new Headers({ "x-forwarded-for": "127.0.0.1" }) }));
vi.mock("next/navigation", () => ({ notFound: () => { throw new Error("NOT_FOUND"); } }));
const hr: CurrentUser = { userId: "hr01", name: "인사팀", role: "HR", empNo: null };
const employee = (empNo: string): CurrentUser => ({ userId: empNo.toLowerCase(), name: empNo, role: "EMPLOYEE", empNo });

it("STEP 15: 8.4의 1~23을 연결해 실제 업무 서비스·직원 화면·인쇄 HTML·CSV·메일·알림 검증", async () => {
  if (process.env.DATABASE_URL !== "file:test.db") throw new Error("테스트 전용 DB가 아닙니다.");
  vi.stubGlobal("React", React);
  vi.mocked(requireRole).mockResolvedValue(hr);
  vi.mocked(getCurrentUser).mockResolvedValue(hr);
  await seedAll();
  const roundId = await createRound(hr, { name: "2027년 상반기 정기승진", baseDate: "2026-12-31", applyStart: "2027-01-04", applyEnd: "2027-01-15" });
  expect((await db.select().from(s.promotionRound))[0].status).toBe("PREPARING");
  await runSelection(hr, roundId);
  const initial = await db.select().from(s.promotionCandidate);
  expect(initial).toHaveLength(11);
  expect(initial.filter((r) => r.autoSelected === "Y")).toHaveLength(5);
  await setManualAction(hr, roundId, "U1003", "ADD", "휴직기간 산정 이의신청 인정");
  await runSelection(hr, roundId);
  const candidates = await db.select().from(s.promotionCandidate);
  expect(candidates.filter((r) => r.finalSelected === "Y")).toHaveLength(6);
  expect(candidates.find((r) => r.empNo === "U1003")).toMatchObject({ manualAction: "ADD", manualReason: "휴직기간 산정 이의신청 인정" });
  await changeRoundStatus(hr, roundId, "APPLYING");
  const apps = await db.select().from(s.application);
  const app = (empNo: string) => apps.find((r) => r.empNo === empNo)!;
  expect(apps).toHaveLength(6);
  expect(apps.every((r) => r.status === "NOT_STARTED")).toBe(true);
  expect(await db.select().from(s.applicationItem)).toHaveLength(90);
  expect((await db.select().from(s.mailOutbox)).map((r) => r.toEmpNo).sort()).toEqual(["U1001", "U1003", "U1004", "U1006", "U1007", "U1012"]);
  const input = { achievement: "주요 업무실적", plan: "자기개발 계획" };
  await requestCorrection(employee("U1004"), app("U1004").appId, { itemKey: "training_2025", requestedValue: "32", reason: "외부 위탁교육 12시간 누락" });
  expect(await unreadNotificationCount(hr)).toBe(1);
  const [request] = await db.select().from(s.correctionRequest);
  const beforeFailure = await db.select().from(s.application);
  await expect(submitApplication(employee("U1004"), app("U1004").appId, input)).rejects.toMatchObject({ code: "PENDING_CORRECTION" });
  expect(await db.select().from(s.application)).toEqual(beforeFailure);
  await approveCorrection(hr, request.reqId, "32");
  expect((await db.select().from(s.applicationItem).where(and(eq(s.applicationItem.appId, app("U1004").appId), eq(s.applicationItem.itemKey, "training_2025"))))[0]).toMatchObject({ erpValue: "20", currentValue: "32" });
  await submitApplication(employee("U1004"), app("U1004").appId, input);
  await requestCorrection(employee("U1001"), app("U1001").appId, { itemKey: "awards", requestedValue: "2026-05-10 우수직원 표창", reason: "포상 누락" });
  const pending = (await db.select().from(s.correctionRequest)).find((r) => r.status === "PENDING")!;
  const feedback = "ERP 미등록 포상은 증빙과 함께 인사팀에 별도 등록 요청 바랍니다";
  await rejectCorrection(hr, pending.reqId, feedback);
  vi.mocked(requireRole).mockResolvedValue(employee("U1001"));
  expect(renderToStaticMarkup(await MyPromotionPage())).toContain(feedback);
  expect((await db.select().from(s.applicationItem).where(and(eq(s.applicationItem.appId, app("U1001").appId), eq(s.applicationItem.itemKey, "awards"))))[0].currentValue).toBe("없음");
  for (const empNo of ["U1001", "U1003", "U1006", "U1007"]) await submitApplication(employee(empNo), app(empNo).appId, input);
  await changeRoundStatus(hr, roundId, "REVIEWING");
  vi.mocked(requireRole).mockResolvedValue(employee("U1012"));
  const unsubmitted = renderToStaticMarkup(await MyPromotionPage());
  expect(unsubmitted).toContain("현재 회차에서는 작성·제출할 수 없습니다.");
  expect(unsubmitted).not.toContain('name="achievement"');
  expect((await db.select().from(s.application).where(eq(s.application.appId, app("U1012").appId)))[0].status).toBe("NOT_STARTED");
  await returnApplication(hr, app("U1006").appId, "업무실적을 구체적인 수치로 보완해 주세요");
  await expect(changeRoundStatus(hr, roundId, "RESULT")).rejects.toMatchObject({ code: "REVIEW_PENDING" });
  vi.mocked(requireRole).mockResolvedValue(employee("U1006"));
  expect(renderToStaticMarkup(await MyPromotionPage())).toContain('name="achievement"');
  await submitApplication(employee("U1006"), app("U1006").appId, { ...input, achievement: "개선율 30%" });
  const submitted = ["U1001", "U1003", "U1004", "U1006", "U1007"];
  for (const empNo of submitted) await confirmApplication(hr, app(empNo).appId);
  vi.mocked(requireRole).mockResolvedValue(hr);
  const printHtml = renderToStaticMarkup(await ReviewPage({ params: Promise.resolve({ roundId: String(roundId) }), searchParams: Promise.resolve({}) }));
  expect(printHtml.match(/<article/g)).toHaveLength(5);
  expect(printHtml).not.toContain("오세린");
  const data = new FormData(); data.set("reason", "2027 상반기 승진심사위원회 자료");
  const csv = await POST(new Request("http://localhost/csv", { method: "POST", body: data }), { params: Promise.resolve({ roundId: String(roundId) }) });
  expect(csv.status).toBe(200);
  expect((await csv.text()).trimEnd().split("\r\n")).toHaveLength(6);
  expect((await db.select().from(s.accessLog)).map((r) => r.action).sort()).toEqual(["DOWNLOAD", "PRINT", "UPDATE"]);
  await changeRoundStatus(hr, roundId, "RESULT");
  for (const empNo of submitted) await registerResult(hr, app(empNo).appId, ["U1001", "U1004", "U1007"].includes(empNo) ? "PROMOTED" : "NOT_PROMOTED");
  vi.mocked(requireRole).mockResolvedValue(employee("U1004"));
  expect(renderToStaticMarkup(await MyPromotionPage())).not.toContain("심사 결과:");
  expect(await notifyResults(hr, roundId)).toBe(5);
  expect(await notifyResults(hr, roundId)).toBe(0);
  expect(renderToStaticMarkup(await MyPromotionPage())).toContain("<strong>승진</strong>");
  const inbox = renderToStaticMarkup(await MyMailsPage());
  expect(inbox.match(/<details/g)).toHaveLength(2);
  expect(inbox).not.toContain("김지훈");
  const mails = await db.select().from(s.mailOutbox);
  expect(mails.filter((r) => r.mailType === "PROMO_INVITE")).toHaveLength(6);
  expect(mails.filter((r) => r.mailType === "PROMO_RESULT")).toHaveLength(5);
  expect(new Set(mails.map((r) => r.dedupKey)).size).toBe(11);
  const counts: Record<string, number> = {};
  for (const row of await db.select().from(s.processHistory).where(eq(s.processHistory.entityType, "APPLICATION"))) counts[row.action] = (counts[row.action] ?? 0) + 1;
  expect(counts).toEqual({ APP_CREATED: 6, APP_DRAFTED: 5, APP_SUBMITTED: 6, APP_RETURNED: 1, APP_CONFIRMED: 5, RESULT_REGISTERED: 5, RESULT_NOTIFIED: 5 });
  expect(await unreadNotificationCount(hr)).toBe(8);
  const notifications = await listNotifications(hr);
  const target = notifications.find((r) => r.type === "APPLICATION_SUBMITTED")!;
  expect(target.link).toBe(`/hr/rounds/${roundId}/applications`);
  expect(await openNotification(hr, target.notiId)).toBe(target.link);
  expect(await unreadNotificationCount(hr)).toBe(7);
  expect((await listNotifications(hr)).find((r) => r.notiId === target.notiId)?.readYn).toBe("Y");
});

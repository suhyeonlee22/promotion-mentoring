import * as React from "react";
import { renderToStaticMarkup } from "react-dom/server";
import { expect, it, vi } from "vitest";
import { eq } from "drizzle-orm";
import { db } from "@/db/client";
import { seedAll } from "@/db/seed";
import * as s from "@/db/schema";
import { createRound, runSelection, setManualAction, changeRoundStatus } from "@/services/rounds";
import { saveDraft, requestCorrection, rejectCorrection, approveCorrection, submitApplication, returnApplication, confirmApplication, registerResult, notifyResults } from "@/services/applications";
import { recalcAll, bulkConfirmMatched } from "@/services/steps";
import { saveAppointment } from "@/services/mock-erp";
import ApplicationPage from "./applications/[appId]/page";
import StepPage from "./steps/[empNo]/page";
import ReviewPage from "./rounds/[roundId]/review-data/page";
import { POST } from "./rounds/[roundId]/review-data/csv/route";
import MyPage from "../me/page";
import { requireRole, getCurrentUser } from "@/lib/session";
vi.mock("@/lib/session", () => ({ requireRole: vi.fn(), getCurrentUser: vi.fn() }));
vi.mock("next/headers", () => ({ headers: vi.fn(async () => new Headers({ "x-forwarded-for": "192.0.2.10, 192.0.2.11" })) }));
const hr = { userId: "hr01", name: "인사팀", role: "HR" as const, empNo: null };
const employee = { userId: "u1001", name: "김지훈", role: "EMPLOYEE" as const, empNo: "U1001" };
it("4.1 처리 코드 19종 및 4.2 접근기록 5가지 실제 업무 연결 검증", async () => {
  if (process.env.DATABASE_URL !== "file:test.db") throw new Error("테스트 전용 DB가 아닙니다.");
  vi.stubGlobal("React", React); vi.mocked(requireRole).mockResolvedValue(hr); vi.mocked(getCurrentUser).mockResolvedValue(hr);
  await seedAll();
  const roundId = await createRound(hr, { name: "감사 검증", baseDate: "2026-12-31", applyStart: "2027-01-04", applyEnd: "2027-01-15" });
  await runSelection(hr, roundId);
  await setManualAction(hr, roundId, "U1003", "ADD", "불산입 이의 인정");
  await setManualAction(hr, roundId, "U1003", "NONE", "");
  await setManualAction(hr, roundId, "U1004", "EXCLUDE", "예외 제외 검증");
  await setManualAction(hr, roundId, "U1004", "NONE", "");
  await changeRoundStatus(hr, roundId, "APPLYING");
  const [app] = await db.select().from(s.application).where(eq(s.application.empNo, "U1001"));
  const input = { achievement: "감사 검증 업무실적", plan: "계획" };
  await saveDraft(employee, app.appId, input);
  await requestCorrection(employee, app.appId, { itemKey: "awards", requestedValue: "우수상", reason: "포상 누락" });
  const [req] = await db.select().from(s.correctionRequest);
  await rejectCorrection(hr, req.reqId, "증빙 미비");
  await requestCorrection(employee, app.appId, { itemKey: "awards", requestedValue: "우수상", reason: "증빙 보완" });
  const reqs = await db.select().from(s.correctionRequest);
  await approveCorrection(hr, reqs.find((r) => r.status === "PENDING")!.reqId, "우수상");
  await submitApplication(employee, app.appId, input);
  await returnApplication(hr, app.appId, "업무 내용 보완");
  await submitApplication(employee, app.appId, input);
  await confirmApplication(hr, app.appId);
  await changeRoundStatus(hr, roundId, "REVIEWING"); await changeRoundStatus(hr, roundId, "RESULT");
  await registerResult(hr, app.appId, "PROMOTED"); await notifyResults(hr, roundId);
  await recalcAll(hr); await bulkConfirmMatched(hr);
  await saveAppointment(hr, "ADD", { apptId: "AUDIT-OPEN", empNo: "U1001", apptType: "LEAVE", subType: "SICK", startDate: "2026-11-10", endDate: null, stepAfter: null, gradeAfter: null, memo: null });
  await recalcAll(hr);
  const histories = await db.select().from(s.processHistory);
  expect(new Set(histories.map((h) => h.action))).toEqual(new Set([
    "ROUND_CREATED", "ROUND_STATUS_CHANGED", "SELECTION_RUN", "MANUAL_ADD", "MANUAL_EXCLUDE", "MANUAL_CANCEL",
    "APP_CREATED", "APP_DRAFTED", "APP_SUBMITTED", "APP_RETURNED", "APP_CONFIRMED", "RESULT_REGISTERED", "RESULT_NOTIFIED",
    "CORRECTION_REQUESTED", "CORRECTION_APPROVED", "CORRECTION_REJECTED", "STEP_CALCULATED", "STEP_CONFIRMED", "STEP_REVIEW_NEEDED",
  ]));
  expect(histories.every((h) => !!h.actor && !!h.actedAt)).toBe(true);
  const nullChange = histories.find((h) => h.action === "STEP_CALCULATED" && h.detailJson && JSON.parse(h.detailJson).after === null);
  expect(JSON.parse(nullChange!.detailJson!)).toEqual({ before: "2027-03-01", after: null });
  const count = histories.length; await recalcAll(hr);
  expect(await db.select().from(s.processHistory)).toHaveLength(count);
  renderToStaticMarkup(await ApplicationPage({ params: Promise.resolve({ appId: String(app.appId) }), searchParams: Promise.resolve({}) }));
  renderToStaticMarkup(await StepPage({ params: Promise.resolve({ empNo: "U1001" }), searchParams: Promise.resolve({}) }));
  renderToStaticMarkup(await ReviewPage({ params: Promise.resolve({ roundId: String(roundId) }), searchParams: Promise.resolve({}) }));
  const data = new FormData(); data.set("reason", "승진심사위원회 제출");
  const response = await POST(new Request("http://localhost/csv", { method: "POST", body: data }), { params: Promise.resolve({ roundId: String(roundId) }) });
  expect(response.status).toBe(200);
  const logs = await db.select().from(s.accessLog);
  expect(logs).toHaveLength(5);
  expect(logs.map((r) => r.action)).toEqual(["UPDATE", "VIEW", "VIEW", "PRINT", "DOWNLOAD"]);
  expect(logs.every((r) => r.userId === "hr01" && r.subjectEmpNo === "U1001" && r.ip === "192.0.2.10" && !!r.actedAt && !!r.target)).toBe(true);
  expect(logs.find((r) => r.action === "DOWNLOAD")?.reason).toBe("승진심사위원회 제출");
  vi.mocked(requireRole).mockResolvedValue(employee);
  renderToStaticMarkup(await MyPage());
  expect(await db.select().from(s.accessLog)).toHaveLength(5);
});
